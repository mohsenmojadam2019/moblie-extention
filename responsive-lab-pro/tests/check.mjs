import fs from 'node:fs';import vm from 'node:vm';import assert from 'node:assert/strict';import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const get=p=>fs.readFileSync(path.join(root,p),'utf8');
const manifest=JSON.parse(get('manifest.json'));
assert.equal(manifest.manifest_version,3);
assert.ok(manifest.permissions.includes('sidePanel') && manifest.permissions.includes('debugger'));
assert.equal(manifest.side_panel.default_path,'panel.html');
const context=vm.createContext({});vm.runInContext(get('devices.js')+';globalThis.presets=DEVICE_PRESETS;globalThis.widths=QUICK_WIDTHS;',context);
assert.ok(context.presets.length>=15);
assert.equal(new Set([...context.presets].map(x=>x.id)).size,context.presets.length);
assert.ok([...context.presets].every(x=>x.width>=240&&x.width<=2560&&x.height>=320&&x.height<=2560&&x.dpr>0));
assert.deepEqual([...context.widths],[320,360,375,390,414,768,1024,1280]);
for(const f of ['background.js','content.js','panel.js','devices.js'])new vm.Script(get(f),{filename:f});
for(const file of ['background.js','content.js','panel.js','devices.js'])assert.ok(fs.statSync(path.join(root,file)).size>500);
assert.ok(get('panel.html').includes('id="device"')&&get('panel.html').includes('id="css-text"'));
assert.ok(get('background.js').includes('Emulation.setDeviceMetricsOverride'));
assert.ok(get('background.js').includes('Page.captureScreenshot'));
for(const n of [16,48,128])assert.ok(fs.existsSync(path.join(root,`icons/icon${n}.png`)));
console.log(`PASS — MV3 manifest, ${context.presets.length} presets, emulation, picker, audit, screenshot, export and JS syntax`);
